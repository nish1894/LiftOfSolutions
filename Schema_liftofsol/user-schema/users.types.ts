// users and auth_identities collections.
// users: one document per person. Every user is a customer; the free or paid plan is on
// their organization.
// auth_identities: how that person signs in, kept apart so the login system can change
// (Firebase today, our own later) without touching users or anything that points to them.
// Works for Firestore and MongoDB. Dates are JS Date objects in app code;
// each driver converts them (BSON Date in MongoDB, Timestamp in Firestore).
// Keys: PK = primary key, FK = foreign key, UNIQUE = no two documents share the value.
//
// Rules enforced in code:
// - users._id is ours and never changes; every other collection points to the user by it.
// - Sign-in: verify the token, find auth_identities by provider + subject, use its user_id.
//   That link never changes, so the API can cache (provider + subject) → user_id in memory.
// - First sign-in creates the user, its identity and the membership in one transaction.
//   Any new user with no organization attached gets their own organization
//   (e.g. "Asha's workspace") on the default plan, with them as owner. A new user who signs up
//   through an invite joins that organization instead. Which plan is the default is set in Billing.
// - A user always keeps at least one identity; removing the last one is refused.
// - After sign-in, a user whose status isn't "active" is refused.
// - Email is never the link between a login and a user.
// - display_name falls back to the part of the email before "@" when sign-in gives no name.
// - dob and gender are optional, never required to sign up, and cleared when the account is deleted.
// - A user belongs to exactly one organization.
// - Joining another organization moves the user's membership there. Their projects stay behind
//   in the old organization, which is closed. Only offered while they are its only member.
// - Becoming a company updates their own organization in place (name, slug, plan); nothing moves.
// - terms_accepted_at and terms_version are set together. Missing = not accepted yet;
//   ask before they use the app.
// - status "deleted" and deleted_at are set together, and only together.
// - Passwords never go in users. Our own login, if added later, gets a separate
//   password_credentials collection (user_id UNIQUE, password_hash, password_changed_at).

import type { OrgRole } from "../shared.types";

// ---------- users ----------

export type UserStatus = "active" | "suspended" | "deleted";

export type Theme = "light" | "dark" | "system";

export interface UserSettings {
  theme?: Theme;
  language?: string;  // BCP 47, e.g. "en", "hi-IN"
  timezone?: string;  // IANA, e.g. "Asia/Kolkata"
  notifications?: {
    email?: boolean;           // account and activity emails
    product_updates?: boolean; // marketing emails; opt-in only, missing = false
  };
}

// A user belongs to exactly one organization (Organization schema).
export interface Membership {
  org_id: string;          // FK → organizations._id
  role: OrgRole;
  created_at: Date;
  updated_at: Date;
}

export interface User {
  _id: string;             // PK. UUID v4, generated by the app
  display_name: string;
  email?: string;          // lowercase contact email; UNIQUE when present
  phone?: string;          // E.164, e.g. "+919812345678"
  avatar_url?: string;
  dob?: string;            // date of birth, "YYYY-MM-DD"
  gender?: string;
  status: UserStatus;
  membership: Membership;  // always set; the organization holds the plan
  settings?: UserSettings;
  terms_accepted_at?: Date;
  terms_version?: string;  // e.g. "2026-10"
  created_at: Date;
  updated_at: Date;
  deleted_at?: Date;       // with status "deleted"; purge after a grace period
}

// ---------- auth_identities ----------
// A user has 1 or more. UNIQUE together: provider + subject.

// Who verified the sign-in. Firebase covers Google, GitHub and email + password.
export type IdentityProvider = "firebase" | "local";

export interface AuthIdentity {
  _id: string;             // PK. UUID v4
  user_id: string;         // FK → users._id
  provider: IdentityProvider;
  subject: string;         // Firebase uid, or our own credential id for local login
  created_at: Date;
}
